_G = _bauen()
# "(" and ")" are built with helper calls above; make sure ")" is the mirror image of "("
_G[")"] = (1.75, _spiegel(_G["("][1], 1.75))
_LEER = (4.0, [[(0, 0), (4, 0), (4, 7), (0, 7), (0, 0)]])      # missing character: box


def glyphe(ch):
    return _G.get(ch, _LEER)


def schritt(ch):
    """Advance of a character in units (width + gap; space = word gap)."""
    if ch == " ":
        return WORT
    return glyphe(ch)[0] + ABSTAND


def zeilenbreite_einheiten(zeile):
    if not zeile:
        return 0.0
    return max(0.0, sum(schritt(c) for c in zeile) - ABSTAND)


def breite(inhalt, hoehe):
    """Width of the widest line in drawing units for cap height `hoehe`."""
    f = hoehe / KAPPE
    return max([zeilenbreite_einheiten(z) for z in (inhalt or "").split("\n")] or [0.0]) * f


def strichbreite(hoehe, fett=False):
    return hoehe * (0.15 if fett else 0.10)


def zeile_zuege(zeile, hoehe, kursiv=False):
    """Polylines of one line: baseline at y = 0, start at x = 0, y up, in drawing units."""
    f = hoehe / KAPPE
    t = math.tan(NEIGUNG) if kursiv else 0.0
    out = []
    x0 = 0.0
    for ch in zeile:
        if ch == " ":
            x0 += WORT
            continue
        w, zuege = glyphe(ch)
        for z in zuege:
            out.append([((x0 + px + py * t) * f, py * f) for (px, py) in z])
        x0 += w + ABSTAND
    return out
