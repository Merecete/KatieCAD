"""KatieCAD Normschrift: single-stroke lettering for drawings (own design, MIT).

Proportions follow ISO 3098 / DIN 6776 type B: cap height h = 10 units, lower case 7/10 h
(ascenders 10/10 h, descenders 3/10 h), stroke width 1/10 h, letter gap 2/10 h, word gap
6/10 h. The letters are drawn from straight pieces and ellipse arcs, so the font looks
the same on every computer, on screen and in the PDF. Two fonts: upright and slanted (15 deg).

Glyph data: char -> (width, [polyline, ...]) in units with the baseline at y = 0.
"""
import math

NAME = "KatieCAD Normschrift"
NAME_KURSIV = "KatieCAD Normschrift kursiv"
NAMEN = (NAME, NAME_KURSIV)

KAPPE = 10.0          # cap height in units
ABSTAND = 2.5         # gap between letters
WORT = 6.0            # word gap (space)
ZEILE = 17.0          # line pitch / 10 (17/10 h as in the standard)
NEIGUNG = math.radians(15.0)


def ist_normschrift(name):
    return str(name) in NAMEN


def ist_kursiv(name):
    return str(name) == NAME_KURSIV


def _arc(cx, cy, rx, ry, a0, a1, n=None):
    """Ellipse arc from angle a0 to a1 (degrees; a1 < a0 runs clockwise)."""
    if n is None:
        n = max(6, int(abs(a1 - a0) / 12.0) + 1)
    out = []
    for i in range(n + 1):
        a = math.radians(a0 + (a1 - a0) * i / n)
        out.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return out


def _oval(cx, cy, rx, ry):
    return _arc(cx, cy, rx, ry, 90, 450, 30)


def _punkt(x, y):
    return [(x, y), (x, y + 0.3)]


def _tf(zuege, sx=1.0, sy=1.0, dx=0.0, dy=0.0):
    return [[(x * sx + dx, y * sy + dy) for (x, y) in z] for z in zuege]


def _spiegel(zuege, breite):
    return [[(breite - x, y) for (x, y) in z] for z in zuege]


